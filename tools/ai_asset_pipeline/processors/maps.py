"""Tileable PBR maps.

Procedural maps are generated from wrapped noise. Maps derived from an albedo
are labeled by the caller as derived_from_albedo and are not a second AI model.
"""

from pathlib import Path

from PIL import Image, ImageFilter


def _fade(t: float) -> float:
    return t * t * (3.0 - 2.0 * t)


def _hash(ix: int, iy: int, seed: int) -> float:
    ix = int(ix)
    iy = int(iy)
    seed = int(seed)
    n = (ix * 374761393 + iy * 668265263 + seed * 1442695040) & 0xFFFFFFFF
    n = (n ^ (n >> 13)) * 1274126177 & 0xFFFFFFFF
    return (n & 0xFFFFFF) / float(0xFFFFFF)


def _noise(x: float, y: float, cells: int, seed: int) -> float:
    x = x % cells
    y = y % cells
    x0 = int(x) % cells
    y0 = int(y) % cells
    x1 = (x0 + 1) % cells
    y1 = (y0 + 1) % cells
    tx = _fade(x - int(x))
    ty = _fade(y - int(y))
    v00 = _hash(x0, y0, seed)
    v10 = _hash(x1, y0, seed)
    v01 = _hash(x0, y1, seed)
    v11 = _hash(x1, y1, seed)
    a = v00 + (v10 - v00) * tx
    b = v01 + (v11 - v01) * tx
    return a + (b - a) * ty


def _fbm(x: float, y: float, cells: int, seed: int) -> float:
    value = 0.0
    weight = 0.0
    amplitude = 1.0
    frequency = 1
    for octave in range(4):
        value += amplitude * _noise(x * frequency, y * frequency, cells * frequency, seed + octave * 17)
        weight += amplitude
        amplitude *= 0.5
        frequency *= 2
    return value / weight


def _hex(value: str) -> tuple[int, int, int]:
    text = value.lstrip("#")
    return tuple(int(text[i : i + 2], 16) for i in (0, 2, 4))


def _mix(colors: list[tuple[int, int, int]], t: float) -> tuple[int, int, int]:
    if len(colors) == 1:
        return colors[0]
    scaled = max(0.0, min(0.9999, t)) * (len(colors) - 1)
    index = int(scaled)
    local = scaled - index
    a = colors[index]
    b = colors[min(index + 1, len(colors) - 1)]
    return tuple(int(a[channel] + (b[channel] - a[channel]) * local) for channel in range(3))


def procedural_maps(size: int, colors: list[str], seed: int, roughness: float, metallic: float) -> dict[str, Image.Image]:
    if size < 8:
        raise ValueError("texture size must be at least 8")
    palette = [_hex(color) for color in colors] or [(137, 146, 157)]
    cells = 8
    height = [0.0] * (size * size)
    albedo = Image.new("RGB", (size, size))
    pixels = albedo.load()
    for y in range(size):
        for x in range(size):
            nx = x / size * cells
            ny = y / size * cells
            h = _fbm(nx, ny, cells, seed)
            height[y * size + x] = h
            warp = _fbm(nx + 3.1, ny + 1.7, cells, seed + 90)
            color = _mix(palette, (h * 0.75 + warp * 0.25))
            shade = 0.82 + 0.28 * h
            pixels[x, y] = tuple(max(0, min(255, int(channel * shade))) for channel in color)

    normal = Image.new("RGB", (size, size))
    rough = Image.new("RGB", (size, size))
    ao = Image.new("RGB", (size, size))
    metal = Image.new("RGB", (size, size))
    height_img = Image.new("RGB", (size, size))
    n_px = normal.load()
    r_px = rough.load()
    a_px = ao.load()
    m_px = metal.load()
    h_px = height_img.load()
    metal_byte = max(0, min(255, int(metallic * 255)))
    for y in range(size):
        for x in range(size):
            left = height[y * size + (x - 1) % size]
            right = height[y * size + (x + 1) % size]
            down = height[((y - 1) % size) * size + x]
            up = height[((y + 1) % size) * size + x]
            dx = (right - left) * 4.0
            dy = (up - down) * 4.0
            nz = 1.0
            length = (dx * dx + dy * dy + nz * nz) ** 0.5
            n_px[x, y] = (
                int((-dx / length * 0.5 + 0.5) * 255),
                int((dy / length * 0.5 + 0.5) * 255),
                int((nz / length * 0.5 + 0.5) * 255),
            )
            h_value = height[y * size + x]
            rough_value = max(0.0, min(1.0, roughness + (0.5 - h_value) * 0.18))
            rough_byte = int(rough_value * 255)
            r_px[x, y] = (rough_byte, rough_byte, rough_byte)
            cavity = max(0.0, 0.55 - h_value)
            ao_byte = int(max(0.0, min(1.0, 1.0 - cavity * 1.4)) * 255)
            a_px[x, y] = (ao_byte, ao_byte, ao_byte)
            m_px[x, y] = (metal_byte, metal_byte, metal_byte)
            height_byte = int(h_value * 255)
            h_px[x, y] = (height_byte, height_byte, height_byte)
    return {
        "albedo": albedo,
        "normal": normal,
        "roughness": rough,
        "ao": ao,
        "metallic": metal,
        "height": height_img,
    }


def derive_maps(albedo: Image.Image, roughness: float, metallic: float) -> dict[str, Image.Image]:
    """Build aligned PBR companions from an albedo. These are derived, not generated by an image model."""
    image = albedo.convert("RGB")
    size = image.size
    gray = image.convert("L")
    height = gray.filter(ImageFilter.GaussianBlur(radius=1))
    width, height_px = size
    src = height.load()
    normal = Image.new("RGB", size)
    rough = Image.new("RGB", size)
    ao = Image.new("RGB", size)
    metal = Image.new("RGB", size)
    n_px = normal.load()
    r_px = rough.load()
    a_px = ao.load()
    m_px = metal.load()
    metal_byte = max(0, min(255, int(metallic * 255)))
    for y in range(height_px):
        for x in range(width):
            left = src[(x - 1) % width, y]
            right = src[(x + 1) % width, y]
            down = src[x, (y - 1) % height_px]
            up = src[x, (y + 1) % height_px]
            dx = (right - left) / 255.0 * 3.0
            dy = (up - down) / 255.0 * 3.0
            nz = 1.0
            length = (dx * dx + dy * dy + nz * nz) ** 0.5
            n_px[x, y] = (
                int((-dx / length * 0.5 + 0.5) * 255),
                int((dy / length * 0.5 + 0.5) * 255),
                int((nz / length * 0.5 + 0.5) * 255),
            )
            sample = src[x, y] / 255.0
            rough_value = max(0.0, min(1.0, roughness + (0.5 - sample) * 0.15))
            rough_byte = int(rough_value * 255)
            r_px[x, y] = (rough_byte, rough_byte, rough_byte)
            ao_byte = int(max(80, min(255, 40 + src[x, y])))
            a_px[x, y] = (ao_byte, ao_byte, ao_byte)
            m_px[x, y] = (metal_byte, metal_byte, metal_byte)
    return {
        "albedo": image,
        "normal": normal,
        "roughness": rough,
        "ao": ao,
        "metallic": metal,
        "height": height.convert("RGB"),
    }


def save_maps(maps: dict[str, Image.Image], folder: Path) -> dict[str, str]:
    folder.mkdir(parents=True, exist_ok=True)
    written = {}
    for name, image in maps.items():
        path = folder / f"{name}.png"
        image.save(path, format="PNG")
        written[name] = str(path)
    return written


def tiled_preview(albedo: Image.Image, repeats: int = 3) -> Image.Image:
    width, height = albedo.size
    canvas = Image.new("RGB", (width * repeats, height * repeats))
    for y in range(repeats):
        for x in range(repeats):
            canvas.paste(albedo, (x * width, y * height))
    return canvas


def seam_score(image: Image.Image) -> float:
    """Mean RGB difference across the horizontal and vertical wrap."""
    rgb = image.convert("RGB")
    width, height = rgb.size
    pixels = rgb.load()
    total = 0.0
    count = 0
    for y in range(height):
        a = pixels[0, y]
        b = pixels[width - 1, y]
        total += abs(a[0] - b[0]) + abs(a[1] - b[1]) + abs(a[2] - b[2])
        count += 3
    for x in range(width):
        a = pixels[x, 0]
        b = pixels[x, height - 1]
        total += abs(a[0] - b[0]) + abs(a[1] - b[1]) + abs(a[2] - b[2])
        count += 3
    return total / max(1, count)
